def lang():
    s = get_settings()["language"]
    if s in ("tr", "en"):
        return s
    try:
        from Components.Language import language
        return "tr" if language.getLanguage()[:2] == "tr" else "en"
    except Exception:
        return "en"


def _(text):
    if lang() == "tr":
        return TR.get(text, text)
    return text
